// Directories Blizzard creates per game version. A flavor dir holds Interface/AddOns and WTF.
var knownFlavors = []string{
	"_retail_", "_classic_", "_classic_era_", "_ptr_", "_xptr_", "_beta_",
	"_classic_ptr_", "_classic_era_ptr_", "_classic_beta_",
}

